# Helpers shared by the tests.
#
# The files in fixtures/ were written by inst/validation/python/make_fixtures.py,
# which computes the expected values with code independent of the package.

fixture <- function(name) {
  utils::read.csv(testthat::test_path("fixtures", name), stringsAsFactors = FALSE)
}

# endpoints of the fixture data sets
fixture_endpoints <- function() {
  list(Endpoint("os", "tte", time = "os_time", event = "os_event"),
       Endpoint("pfs", "tte", time = "pfs_time", event = "pfs_event"),
       Endpoint("resp", "binary", var = "resp"),
       Endpoint("ae", "binary", var = "ae", higher.better = FALSE))
}

# endpoints of the data generated by SimCohorts()
sim_endpoints <- function() {
  list(Endpoint("OS", "tte", time = "os_tte", event = "os_event"),
       Endpoint("PFS", "tte", time = "pfs_tte", event = "pfs_event"),
       Endpoint("ORR", "binary", var = "response"),
       Endpoint("AE", "binary", var = "ae", higher.better = FALSE))
}

test_arms <- function() {
  list(Cohort1 = CorOncoEndpoints::OncoArm(pfs.median = 8, orr = 0.45, resp.cor = 0.4,
                                           death.prop = 0.15, os.median = 18),
       Cohort2 = CorOncoEndpoints::OncoArm(pfs.median = 6, orr = 0.30, resp.cor = 0.4,
                                           death.prop = 0.15, os.median = 15))
}
