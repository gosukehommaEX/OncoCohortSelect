test_that("binary and time-to-event endpoints are defined", {
  e1 <- Endpoint("ORR", "binary", var = "response")
  expect_s3_class(e1, "Endpoint")
  expect_identical(e1$type, "binary")
  expect_identical(e1$var, "response")
  expect_true(e1$higher.better)
  e2 <- Endpoint("OS", "tte", time = "os_tte", event = "os_event")
  expect_identical(e2$type, "tte")
  expect_identical(c(e2$time, e2$event), c("os_tte", "os_event"))
  expect_null(e2$var)
  e3 <- Endpoint("AE", var = "ae", higher.better = FALSE)
  expect_identical(e3$type, "binary")
  expect_false(e3$higher.better)
})

test_that("invalid definitions give errors", {
  expect_error(Endpoint("", var = "x"), "name")
  expect_error(Endpoint("A", "binary"), "var")
  expect_error(Endpoint("A", "binary", var = "x", time = "t"), "time-to-event")
  expect_error(Endpoint("A", "tte", time = "t"), "event")
  expect_error(Endpoint("A", "tte", time = "t", event = "e", var = "x"), "binary")
  expect_error(Endpoint("A", var = "x", higher.better = NA), "higher.better")
  expect_error(Endpoint("A", "count", var = "x"))
})
